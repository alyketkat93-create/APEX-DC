import { NextResponse } from 'next/server';
import { db } from '@/lib/server/db';

export async function GET(req: Request) {
  try {
    const { searchParams } = new URL(req.url);
    const projectId = searchParams.get('projectId') || undefined;

    const drawings = db.getDrawings(projectId).map(d => ({
      id: d.id,
      module: 'Drawings & Submissions',
      moduleKey: 'drawings',
      docNumber: d.drawingNumber,
      title: d.title,
      discipline: d.discipline,
      type: d.drawingType,
      currentRevision: d.currentRevision,
      status: d.reviewStatus,
      originator: d.originator,
      recipient: d.reviewer || 'Consultant',
      preparationDate: d.preparationDate,
      internalReviewDate: d.internalReviewDate,
      submissionDate: d.submissionDate || d.revisionDate,
      consultantReceiptDate: d.consultantReceiptDate,
      consultantResponseDate: d.consultantResponseDate,
      approvalDate: d.approvalDate,
      revisionDate: d.revisionDate,
      closureDate: d.closureDate,
      requiredDate: d.requiredResponseDate,
      requiredApprovalDate: d.requiredResponseDate,
      relatedTransmittalId: d.relatedTransmittalId,
      projectId: d.projectId,
      fileUrl: d.fileUrl,
      documentLinks: d.documentLinks || [],
      linkedApexRecords: d.linkedApexRecords || [],
      hasDateCorrections: d.hasDateCorrections,
      dateCorrectionHistory: d.dateCorrectionHistory,
      updatedAt: d.updatedAt,
    }));

    const submittals = db.getSubmittals(projectId).map(s => ({
      id: s.id,
      module: 'Technical Submittals',
      moduleKey: 'submittals',
      docNumber: s.submittalNumber,
      title: s.title,
      discipline: s.discipline,
      type: s.type,
      currentRevision: s.revisionNumber,
      status: s.reviewStatus,
      originator: s.submittedBy,
      recipient: 'Consultant',
      preparationDate: s.preparationDate,
      internalReviewDate: s.internalReviewDate,
      submissionDate: s.submissionDate,
      consultantReceiptDate: s.consultantReceiptDate,
      consultantResponseDate: s.consultantResponseDate,
      approvalDate: s.actualApprovalDate || s.approvalDate,
      revisionDate: s.revisionDate,
      closureDate: s.closureDate,
      requiredDate: s.requiredApprovalDate,
      requiredApprovalDate: s.requiredApprovalDate,
      projectId: s.projectId,
      fileUrl: s.fileName ? `/mock/submittals/${s.fileName}` : undefined,
      documentLinks: s.documentLinks || [],
      linkedApexRecords: s.linkedApexRecords || [],
      hasDateCorrections: s.hasDateCorrections,
      dateCorrectionHistory: s.dateCorrectionHistory,
      updatedAt: s.updatedAt,
    }));

    const irs = db.getInspectionRequests(projectId).map(i => ({
      id: i.id,
      module: 'Inspection Requests',
      moduleKey: 'irs',
      docNumber: i.irNumber,
      title: `${i.inspectionType} - ${i.buildingZone}`,
      discipline: i.discipline,
      type: i.inspectionType,
      currentRevision: i.drawingRevision || '00',
      status: i.result,
      originator: i.submittedBy,
      recipient: i.consultantInspector || 'Consultant',
      preparationDate: i.preparationDate,
      internalReviewDate: i.internalReviewDate,
      submissionDate: i.contractorRequestDate || i.submissionDate,
      consultantReceiptDate: i.consultantReceiptDate,
      consultantResponseDate: i.consultantResponseDate,
      approvalDate: i.approvalDate || (i.result === 'Accepted' || i.result === 'Accepted with Comments' ? i.closureDate : undefined),
      revisionDate: i.revisionDate,
      closureDate: i.closureDate,
      requiredDate: i.requestedDateTime.split('T')[0],
      requiredApprovalDate: i.requiredApprovalDate || i.requestedDateTime.split('T')[0],
      projectId: i.projectId,
      documentLinks: i.documentLinks || [],
      linkedApexRecords: i.linkedApexRecords || [],
      attachments: i.attachments || [],
      hasDateCorrections: i.hasDateCorrections,
      dateCorrectionHistory: i.dateCorrectionHistory,
      updatedAt: i.updatedAt,
    }));

    const mirs = db.getMaterialInspections(projectId).map(m => ({
      id: m.id,
      module: 'Material Inspections',
      moduleKey: 'mirs',
      docNumber: m.mirNumber,
      title: `${m.materialDescription} (${m.manufacturer})`,
      discipline: 'QA/QC',
      type: 'MIR',
      currentRevision: '00',
      status: m.result,
      originator: m.inspector,
      recipient: m.consultantRep || 'Consultant',
      preparationDate: m.preparationDate,
      internalReviewDate: m.internalReviewDate,
      submissionDate: m.deliveryDate || m.submissionDate,
      consultantReceiptDate: m.consultantReceiptDate,
      consultantResponseDate: m.consultantResponseDate,
      approvalDate: m.approvalDate || (m.result === 'Accepted' || m.result === 'Partially Accepted' ? m.inspectionDate : undefined),
      revisionDate: m.revisionDate,
      closureDate: m.closureDate,
      requiredDate: m.inspectionDate,
      requiredApprovalDate: m.requiredApprovalDate || m.inspectionDate,
      projectId: m.projectId,
      documentLinks: m.documentLinks || [],
      linkedApexRecords: m.linkedApexRecords || [],
      attachments: m.attachments || [],
      hasDateCorrections: m.hasDateCorrections,
      dateCorrectionHistory: m.dateCorrectionHistory,
      updatedAt: m.updatedAt,
    }));

    const rfis = db.getRfis(projectId).map(r => ({
      id: r.id,
      module: 'RFIs',
      moduleKey: 'rfis',
      docNumber: r.rfiNumber,
      title: r.subject,
      discipline: r.discipline,
      type: 'RFI',
      currentRevision: '00',
      status: r.status,
      originator: r.originator,
      recipient: r.recipient,
      preparationDate: r.preparationDate,
      internalReviewDate: r.internalReviewDate,
      submissionDate: r.dateRaised || r.submissionDate,
      consultantReceiptDate: r.consultantReceiptDate,
      consultantResponseDate: r.consultantResponseDate || r.actualResponseDate,
      approvalDate: r.approvalDate || r.actualResponseDate,
      revisionDate: r.revisionDate,
      closureDate: r.closureDate,
      requiredDate: r.requiredResponseDate,
      requiredApprovalDate: r.requiredApprovalDate || r.requiredResponseDate,
      projectId: r.projectId,
      documentLinks: r.documentLinks || [],
      linkedApexRecords: r.linkedApexRecords || [],
      attachments: r.attachments || [],
      hasDateCorrections: r.hasDateCorrections,
      dateCorrectionHistory: r.dateCorrectionHistory,
      updatedAt: r.updatedAt,
    }));

    const cor = db.getCorrespondence(projectId).map(c => ({
      id: c.id,
      module: 'Correspondence',
      moduleKey: 'correspondence',
      docNumber: c.correspondenceNumber,
      title: c.subject,
      discipline: c.discipline,
      type: c.direction,
      currentRevision: '00',
      status: c.status,
      originator: c.sender,
      recipient: c.recipient,
      preparationDate: c.preparationDate,
      internalReviewDate: c.internalReviewDate,
      submissionDate: c.letterDate || c.submissionDate,
      consultantReceiptDate: c.consultantReceiptDate,
      consultantResponseDate: c.consultantResponseDate,
      approvalDate: c.approvalDate || c.receivedDispatchedDate,
      revisionDate: c.revisionDate,
      closureDate: c.closureDate,
      requiredDate: c.responseDeadline,
      requiredApprovalDate: c.requiredApprovalDate || c.responseDeadline,
      projectId: c.projectId,
      documentLinks: c.documentLinks || [],
      linkedApexRecords: c.linkedApexRecords || [],
      attachments: c.attachments || [],
      hasDateCorrections: c.hasDateCorrections,
      dateCorrectionHistory: c.dateCorrectionHistory,
      updatedAt: c.updatedAt,
    }));

    const quality = db.getQualityRecords(projectId).map(q => ({
      id: q.id,
      module: 'Quality & NCRs',
      moduleKey: 'quality',
      docNumber: q.recordNumber,
      title: q.title,
      discipline: q.discipline,
      type: q.recordType,
      currentRevision: '00',
      status: q.status,
      originator: q.responsibleParty,
      recipient: q.verifiedBy || 'Consultant',
      preparationDate: q.preparationDate,
      internalReviewDate: q.internalReviewDate,
      submissionDate: q.issueDate || q.submissionDate,
      consultantReceiptDate: q.consultantReceiptDate,
      consultantResponseDate: q.consultantResponseDate,
      approvalDate: q.approvalDate || (q.status === 'Accepted' || q.status === 'Closed' ? q.closureDate : undefined),
      revisionDate: q.revisionDate,
      closureDate: q.closureDate,
      requiredDate: q.dueDate,
      requiredApprovalDate: q.dueDate,
      projectId: q.projectId,
      documentLinks: q.documentLinks || [],
      linkedApexRecords: q.linkedApexRecords || [],
      attachments: q.attachments || [],
      hasDateCorrections: q.hasDateCorrections,
      dateCorrectionHistory: q.dateCorrectionHistory,
      updatedAt: q.updatedAt,
    }));

    const handover = db.getHandoverItems(projectId).map(h => ({
      id: h.id,
      module: 'Handover & Closeout',
      moduleKey: 'handover',
      docNumber: h.itemNumber,
      title: h.title,
      discipline: h.discipline,
      type: h.category,
      currentRevision: h.latestRevision,
      status: h.approvalStatus,
      originator: 'Technical Office',
      recipient: 'Client / Consultant',
      preparationDate: h.preparationDate,
      internalReviewDate: h.internalReviewDate,
      submissionDate: h.submissionDate,
      consultantReceiptDate: h.consultantReceiptDate,
      consultantResponseDate: h.consultantResponseDate,
      approvalDate: h.approvalDate,
      revisionDate: h.revisionDate,
      closureDate: h.closureDate,
      requiredDate: h.requiredApprovalDate,
      requiredApprovalDate: h.requiredApprovalDate,
      projectId: h.projectId,
      documentLinks: h.documentLinks || [],
      linkedApexRecords: h.linkedApexRecords || [],
      attachments: h.attachments || [],
      hasDateCorrections: h.hasDateCorrections,
      dateCorrectionHistory: h.dateCorrectionHistory,
      updatedAt: h.updatedAt,
    }));

    const masterList = [...drawings, ...submittals, ...irs, ...mirs, ...rfis, ...cor, ...quality, ...handover];
    masterList.sort((a, b) => new Date(b.updatedAt).getTime() - new Date(a.updatedAt).getTime());

    return NextResponse.json({ success: true, data: masterList });
  } catch (err: any) {
    return NextResponse.json({ success: false, error: err.message }, { status: 500 });
  }
}
